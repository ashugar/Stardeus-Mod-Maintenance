#requires -Version 7.0
# Pure generation helpers; importing this file never writes or installs anything.
function Assert-CatalogPath {
    param([string]$Root, [string]$Path)
    $comparison = if ($IsWindows) { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }
    $rootPath = [IO.Path]::GetFullPath($Root).TrimEnd([IO.Path]::DirectorySeparatorChar)
    $cursor = [IO.Path]::GetFullPath($Path)
    if ($cursor -ne $rootPath -and -not $cursor.StartsWith($rootPath + [IO.Path]::DirectorySeparatorChar, $comparison)) { throw 'catalog-path-outside-root' }
    while ($cursor -and ($cursor -eq $rootPath -or $cursor.StartsWith($rootPath + [IO.Path]::DirectorySeparatorChar, $comparison))) {
        if ((Test-Path -LiteralPath $cursor) -and ((Get-Item -LiteralPath $cursor -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'catalog-reparse-point-refused' }
        if ($cursor -eq $rootPath) { break }
        $cursor = [IO.Path]::GetDirectoryName($cursor)
    }
}

function ConvertTo-CatalogCell {
    param([string]$Value)
    return $Value.Replace('&', '&amp;').Replace('<', '&lt;').Replace('>', '&gt;').Replace('\', '&#92;').Replace('|', '&#124;').Replace('[', '&#91;').Replace(']', '&#93;').Replace('`', '&#96;').Replace('*', '&#42;').Replace('_', '&#95;').Replace("`r", ' ').Replace("`n", ' ')
}

function Get-ModCatalogArtifacts {
    param([Parameter(Mandatory)][string]$RepoRoot, [Parameter(Mandatory)][string[]]$TrackedPaths)
    $root = [IO.Path]::GetFullPath($RepoRoot)
    Assert-CatalogPath $root $root
    [string[]]$folders = @($TrackedPaths | Where-Object { $_ -cmatch '^[^/]+/ModInfo\.json$' } | ForEach-Object { $_.Substring(0, $_.IndexOf('/')) })
    [Array]::Sort($folders, [StringComparer]::Ordinal)
    if ($folders.Count -eq 0) { throw 'catalog-no-manifests' }
    $ids = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    $labels = [Collections.Generic.List[object]]::new()
    $lines = [Collections.Generic.List[string]]::new()
    foreach ($line in @('# Mod catalog', '', '<!-- Generated by build/ModMaintenance/Update-ModCatalog.ps1. Do not edit this file directly. -->', '', 'Versions and dependencies come from the current manifests. These entries do not certify compatibility with an installed game build or record publication status.', '', '| Mod | Version | Game version | Dependencies | Contents | Workshop |', '| --- | --- | --- | --- | --- | --- |')) { $lines.Add($line) }
    foreach ($folder in $folders) {
        if ($folder -notmatch '^[A-Za-z0-9][A-Za-z0-9().&_\-]*$' -or $folder.Length -gt 46) { throw 'catalog-folder-needs-policy-review' }
        $modRoot = Join-Path $root $folder
        $manifestPath = Join-Path $modRoot 'ModInfo.json'
        Assert-CatalogPath $root $manifestPath
        $text = [IO.File]::ReadAllText($manifestPath, [Text.UTF8Encoding]::new($false, $true))
        $document = [Text.Json.JsonDocument]::Parse($text)
        try {
            if ($document.RootElement.ValueKind -ne [Text.Json.JsonValueKind]::Object) { throw 'catalog-manifest-object-required' }
            $keys = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
            foreach ($property in $document.RootElement.EnumerateObject()) { if (-not $keys.Add($property.Name)) { throw 'catalog-duplicate-manifest-key' } }
        } finally { $document.Dispose() }
        $manifest = ConvertFrom-Json -InputObject $text -AsHashtable
        foreach ($key in @('Id', 'Name', 'ModVersion', 'GameVersion')) {
            if ($manifest[$key] -isnot [string] -or [string]::IsNullOrWhiteSpace($manifest[$key])) { throw 'catalog-manifest-field-required' }
        }
        if (-not $ids.Add($manifest.Id)) { throw 'catalog-duplicate-mod-id' }
        if ($manifest.ContainsKey('Dependencies') -and $manifest.Dependencies -isnot [object[]]) { throw 'catalog-dependencies-array-required' }
        $dependencies = @($manifest.Dependencies)
        foreach ($dependency in $dependencies) { if ($null -ne $dependency -and ($dependency -isnot [string] -or [string]::IsNullOrWhiteSpace($dependency))) { throw 'catalog-invalid-dependency' } }
        $dependencyText = if (@($dependencies | Where-Object { $null -ne $_ }).Count) { (@($dependencies | Where-Object { $null -ne $_ } | ForEach-Object { ConvertTo-CatalogCell $_ }) -join ', ') } else { '-' }
        $workshop = '-'
        $workshopPath = Join-Path $modRoot 'SteamWorkshopItemId'
        if (($folder + '/SteamWorkshopItemId') -cnotin $TrackedPaths) { throw 'catalog-workshop-marker-required' }
        if (($folder + '/SteamWorkshopItemId') -cin $TrackedPaths) {
            Assert-CatalogPath $root $workshopPath
            $workshopId = [Text.UTF8Encoding]::new($false, $true).GetString([IO.File]::ReadAllBytes($workshopPath)).Trim()
            if ($workshopId -notmatch '\A[1-9][0-9]{0,19}\z') { throw 'catalog-invalid-workshop-id' }
            $workshop = '[Workshop](https://steamcommunity.com/sharedfiles/filedetails/?id=' + $workshopId + ')'
        }
        $libraryRoot = Join-Path $modRoot 'Libraries'
        $contents = 'Data'
        if (@($TrackedPaths | Where-Object { $_.StartsWith($folder + '/Libraries/', [StringComparison]::Ordinal) -and $_.EndsWith('.dll', [StringComparison]::OrdinalIgnoreCase) }).Count) {
            Assert-CatalogPath $root $libraryRoot
            $contents = 'DLL + data'
        }
        $link = [Uri]::EscapeDataString($folder) + '/'
        $lines.Add('| [' + (ConvertTo-CatalogCell $manifest.Name) + '](' + $link + ') | ' + (ConvertTo-CatalogCell $manifest.ModVersion) + ' | ' + (ConvertTo-CatalogCell $manifest.GameVersion) + ' | ' + $dependencyText + ' | ' + $contents + ' | ' + $workshop + ' |')
        $labels.Add([ordered]@{ Folder = $folder; Label = 'mod:' + $folder })
    }
    $catalog = ($lines -join "`n") + "`n"
    $labelMap = [ordered]@{ SchemaVersion = 1; Mods = @($labels.ToArray()); AutomationLabel = 'repository-automation' }
    $labelJson = (ConvertTo-Json -InputObject $labelMap -Depth 8).Replace("`r`n", "`n") + "`n"
    return [pscustomobject]@{ Catalog = $catalog; Labels = $labelJson; Count = $folders.Count }
}
